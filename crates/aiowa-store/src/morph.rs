//! Русские словоформы для поиска без переиндексации (`docs/ai-layer-design.md` § 5.1, решение
//! автора 13.11.2026: морфология на стороне запроса).
//!
//! Индекс FTS5 хранит слова как есть. Слово запроса ищется как набрано (префиксом, как раньше) и
//! ещё точными токенами — своей основой с падежными окончаниями: «договора» находит «договор»,
//! «договору», «договоров», но не «договорённость». Основа — слово без падежного окончания
//! существительного или прилагательного (первый шаг стеммера Snowball для русского);
//! словообразовательные суффиксы не трогаются, поэтому «должности» не превращается в «должен».
//! Беглые гласные («писем», «дней», «поставок») не разбираются.

/// Гласные: окончание снимается только после первой гласной слова (область RV у Snowball).
const VOWELS: [char; 9] = ['а', 'е', 'и', 'о', 'у', 'ы', 'э', 'ю', 'я'];

/// Падежные окончания существительных и прилагательных, длинные первыми.
const ENDINGS: &[&str] = &[
    "иями", "ями", "ами", "ими", "ыми", "его", "ого", "ему", "ому", "ией", "иям", "ием", "иях", "ее", "ие", "ые", "ое", "ей", "ий", "ый", "ой", "ем", "им", "ым", "ом", "их", "ых", "ую", "юю", "ая", "яя", "ою", "ею", "ев", "ов", "ье", "еи", "ии", "ям",
    "ам", "ах", "ях", "ию", "ью", "ия", "ья", "а", "е", "и", "й", "о", "у", "ы", "ь", "ю", "я",
];

/// Окончания, которые не снимаются, но нужны при порождении форм: «статья» → «статьи», «статьями».
const EXTRA_ENDINGS: &[&str] = &["ьи", "ьей", "ьям", "ьями", "ьях", "ьев", "ьем"];

/// Основа короче — слово не разбирается: у коротких основ слишком много чужих слов.
const STEM_MIN: usize = 3;

/// Слово из строчных русских букв (ё уже заменена на е).
fn is_russian_word(word: &str) -> bool {
    !word.is_empty() && word.chars().all(|c| ('а'..='я').contains(&c))
}

/// Основа слова и снятое окончание. `None` — слово не русское, окончания нет или основа короче
/// трёх букв. Слово — в нижнем регистре, ё заменена на е (`text::norm_lower`).
pub fn stem(word: &str) -> Option<(&str, &'static str)> {
    if !is_russian_word(word) {
        return None;
    }
    // Начало области, где можно снимать окончание: сразу после первой гласной.
    let rv = word.char_indices().find(|(_, c)| VOWELS.contains(c)).map(|(i, c)| i + c.len_utf8())?;
    for e in ENDINGS {
        if word.len() >= rv + e.len() && word.ends_with(e) {
            let s = &word[..word.len() - e.len()];
            return (s.chars().count() >= STEM_MIN).then_some((s, *e));
        }
    }
    None
}

/// Другие формы слова: основа и основа с каждым окончанием, без самого слова. Пусто, если у
/// слова нет окончания (тогда все формы и так находит поиск по началу слова).
pub fn forms(word: &str) -> Vec<String> {
    let Some((s, _)) = stem(word) else { return Vec::new() };
    let mut out: Vec<String> = Vec::with_capacity(ENDINGS.len() + EXTRA_ENDINGS.len() + 1);
    out.push(s.to_string());
    for e in ENDINGS.iter().chain(EXTRA_ENDINGS) {
        out.push(format!("{s}{e}"));
    }
    out.retain(|f| f != word);
    out.sort();
    out.dedup();
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn stem_of(w: &str) -> Option<&str> {
        stem(w).map(|(s, _)| s)
    }

    #[test]
    fn strips_case_endings() {
        for (word, expected) in [
            ("договора", "договор"),
            ("договору", "договор"),
            ("договором", "договор"),
            ("договоров", "договор"),
            ("ремонта", "ремонт"),
            ("поставки", "поставк"),
            ("поставкой", "поставк"),
            ("заявками", "заявк"),
            ("акты", "акт"),
            ("счета", "счет"),
            ("счету", "счет"),
            ("компании", "компан"),
            ("здание", "здан"),
            ("историями", "истор"),
            ("линией", "лин"),
            ("нового", "нов"),
            ("новый", "нов"),
            ("красную", "красн"),
            ("очередью", "очеред"),
            ("статьи", "стать"),
            ("иванову", "иванов"),
            ("ивановой", "иванов"),
        ] {
            assert_eq!(stem_of(word), Some(expected), "{word}");
        }
    }

    #[test]
    fn leaves_words_without_ending_and_short_stems() {
        // Нет окончания: формы находит поиск по началу слова.
        for w in ["договор", "ремонт", "акт", "счет", "насос", "отчет"] {
            assert_eq!(stem_of(w), None, "{w}");
        }
        // Основа короче трёх букв — не трогаем.
        for w in ["дня", "мая", "она", "его", "или"] {
            assert_eq!(stem_of(w), None, "{w}");
        }
        // Не русские слова, числа, смешанные.
        for w in ["invoice", "2026", "кп-12", "", "Договора", "счёта"] {
            assert_eq!(stem_of(w), None, "{w}");
        }
        // Окончание снимается только после первой гласной.
        assert_eq!(stem_of("много"), Some("мног"));
        assert_eq!(stem_of("цех"), None);
    }

    #[test]
    fn derivational_suffixes_stay() {
        // «должности» остаётся «должност…», а не «должн…» (иначе нашлось бы «должен»).
        assert_eq!(stem_of("должности"), Some("должност"));
        assert_eq!(stem_of("договоренности"), Some("договоренност"));
    }

    #[test]
    fn generates_forms() {
        let f = forms("договора");
        for expected in ["договор", "договору", "договором", "договоре", "договоры", "договоров", "договорам", "договорами", "договорах"] {
            assert!(f.iter().any(|x| x == expected), "{expected}");
        }
        assert!(!f.iter().any(|x| x == "договора"), "само слово ищется префиксом");
        assert!(!f.iter().any(|x| x.starts_with("договорен")), "однокоренные слова не порождаются");
        // «статья» ↔ «статьи», «статей».
        let f = forms("статья");
        for expected in ["статьи", "статью", "статье", "статей", "статьям", "статьями", "статьях"] {
            assert!(f.iter().any(|x| x == expected), "{expected}");
        }
        let f = forms("статьи");
        for expected in ["статья", "статью", "статье", "статьей", "статьям"] {
            assert!(f.iter().any(|x| x == expected), "{expected}");
        }
        // «очередь» ↔ «очереди», «очередью».
        let f = forms("очереди");
        assert!(f.iter().any(|x| x == "очередь") && f.iter().any(|x| x == "очередью"));
        // Фамилии: «ивановой» → «иванов», «иванова», «иванову», «ивановым».
        let f = forms("ивановой");
        for expected in ["иванов", "иванова", "иванову", "ивановым"] {
            assert!(f.iter().any(|x| x == expected), "{expected}");
        }
        assert!(forms("договор").is_empty() && forms("invoice").is_empty());
        // Без повторов.
        let mut d = forms("поставки");
        let n = d.len();
        d.dedup();
        assert_eq!(n, d.len());
    }
}
